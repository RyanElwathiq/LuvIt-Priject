<?php
/**
 * ============================================================================
 * LUV IT · محاذاة إيميلات ووكومرس · بند الإطلاق ٦.٣
 * ============================================================================
 * سنيبت WPCode من نوع PHP · التشغيل: Run Everywhere
 *
 * ⚠️ أول مسودة لهذا الملف كانت **ثلاثة أضعاف حجمه** وبتصلّح أشياء مش مكسورة.
 *    القياس على معاينة ووكومرس نفسها قال العكس:
 *
 *      dir على <html> ................. rtl        ✅ ووكومرس ضابطها
 *      اتجاه body ..................... rtl        ✅
 *      #body_content_inner ............ right/rtl  ✅
 *      عمود «المنتج» .................. right      ✅
 *
 *    يعني ووكومرس **بيتعامل مع RTL صح**، وما بقي مكسور إلا شي واحد بالضبط:
 *    عناصر عليها `text-align: left` **مكتوبة inline** بقوالب الإضافة.
 *
 *      #template_header h1 ..... inline: left   محسوب: left   🔴
 *      عمود «الكمية» ........... inline: left   محسوب: left   🔴
 *      عمود «السعر» ............ inline: left   محسوب: left   🔴
 *      عمود «تنزيل» ............ inline: left   محسوب: left   🔴
 *
 *    و٤٢ عنصر بالإيميل عليهم محاذاة inline.
 *
 * ============================================================================
 * ليش `!important` هون · وهو ممنوع بباقي المشروع
 * ============================================================================
 * قاعدة المشروع «مضاعفة الكلاس مش !important» بتتكلم عن تصادم قواعدنا مع
 * بعضها بـ`tokens.css`، وهناك المضاعفة بتحل المشكلة لأن الطرفين بستايل شيت.
 *
 * هون الخصم **ستايل inline بقالب PHP** تبع الإضافة، والـinline بيغلب أي محدد
 * مهما كان تخصيصه. `!important` هو **الآلية الوحيدة بالـCSS** اللي بتغلبه.
 *
 * وووكومرس بيمرّر ناتج `woocommerce_email_styles` على مُدمِج (inliner) بيحوّل
 * القواعد لستايلات inline قبل الإرسال، لأن عملاء البريد بيشيلوا `<style>`.
 * المُدمِج بيحترم `!important`، فالقاعدة بتوصل.
 *
 * ⚠️ وولا خاصية منطقية هون (`text-align: start` · `margin-inline-start`):
 *    عملاء البريد بيرندروا بمحركات قديمة وبينضّفوا اللي ما بيعرفوه.
 *    **الفيزيائي هو الصح بالإيميل**، وهاد استثناء مقصود من قاعدة الموقع.
 * ============================================================================
 */

add_filter( 'woocommerce_email_styles', function ( $css, $email = null ) {

	if ( ! is_rtl() ) {
		return $css;
	}

	$css .= '
	/* ===== LUV IT · محاذاة RTL · بس اللي انقاس إنه مكسور ===== */

	#template_header h1 { text-align: right !important; }

	#body_content table.td th,
	#body_content table.td td { text-align: right !important; }

	/* المبلغ بيضل يُقرأ يساراً لليمين جوّا خليّة يمينية، وإلا بتنعكس علامة
	   العملة أو الفاصلة العشرية عند بعض عملاء البريد. العملة معيّنة
	   `right_space` يعني «42.00 د.ا»، وهاد الترتيب لازم يوصل زي ما هو. */
	.amount, .woocommerce-Price-amount {
		direction: ltr !important;
		unicode-bidi: embed;
		display: inline-block;
	}

	/* الخط · بدائل آمنة بالبريد فقط. ولا @font-face: أغلب العملاء بيشيلوه
	   والبديل هو اللي بينرسم فعلاً. */
	body, #body_content, #body_content td, #template_header h1 {
		font-family: "IBM Plex Sans Arabic", "Segoe UI", Tahoma, Arial, sans-serif;
	}
	';

	return $css;
}, 20, 2 );
