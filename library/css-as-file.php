if ( ! defined( 'LUVIT_CSS_SNIPPET_ID' ) ) {
	/* سنيبت «LUVIT Design Tokens» · مصدر الحقيقة الوحيد للستايل */
	define( 'LUVIT_CSS_SNIPPET_ID', 49 );
}

/**
 * بترجّع اسم ملف الستايل الجاهز · وبتبنيه لو تغيّر المصدر.
 *
 * بترجّع '' بأي فشل · والنداء بيفحص إشي واحد.
 */
function luvit_css_file_name() {
	$mod = get_post_field( 'post_modified_gmt', LUVIT_CSS_SNIPPET_ID );
	if ( ! $mod ) {
		return '';
	}

	$up  = wp_upload_dir();
	if ( ! empty( $up['error'] ) ) {
		return '';
	}
	$dir = trailingslashit( $up['basedir'] ) . 'luvit';

	/* المسار السريع · ولا قراءة للمحتوى ولا هاش */
	$cache = get_option( 'luvit_css_file', array() );
	if (
		is_array( $cache )
		&& ! empty( $cache['mod'] ) && $cache['mod'] === $mod
		&& ! empty( $cache['name'] ) && file_exists( $dir . '/' . $cache['name'] )
	) {
		return $cache['name'];
	}

	/* المسار البطيء · بيمرق مرة وحدة بعد كل تعديل */
	$css = get_post_field( 'post_content', LUVIT_CSS_SNIPPET_ID );

	/* 🔴 حارس ١ · قراءة فاشلة أو سنيبت انفرغ */
	if ( ! is_string( $css ) || strlen( $css ) < 100000 ) {
		return '';
	}

	$name = 'tokens-' . substr( md5( $css ), 0, 12 ) . '.css';
	$path = $dir . '/' . $name;

	if ( ! file_exists( $path ) ) {
		wp_mkdir_p( $dir );
		/* النسخ القديمة بتنشال · بصمة المحتوى بالاسم فما في داعي نحتفظ فيهن */
		foreach ( (array) glob( $dir . '/tokens-*.css' ) as $old ) {
			if ( $old !== $path ) {
				wp_delete_file( $old );
			}
		}
		/* 🔴 حارس ٢ · الكتابة فشلت (صلاحيات · قرص ممتلئ) */
		if ( false === file_put_contents( $path, $css ) ) { // phpcs:ignore
			return '';
		}
	}

	update_option( 'luvit_css_file', array( 'mod' => $mod, 'name' => $name ), false );

	return $name;
}

/* ══════════════════════════════════════════════════════════════════════
   🔴 **LUVIT_CSS_ORDER · وهاي أهم سطر بالملف · انكشفت بالقياس ٧ أيلول**
   ══════════════════════════════════════════════════════════════════════
   أول نسخة استعملت `wp_enqueue_style` على `wp_enqueue_scripts` بأولوية ٥.
   **وكانت رح تكسر الموقع بصمت.** المقيس على `<head>` وقت ما الاثنان
   موجودان:

     الكتلة المضمّنة (846KB)  بموقع 180,999   ← **آخر ستايل بالصفحة**
     رابط الملف              بموقع   8,217   ← رقم ٥ من ٤٣
     وبينهن **١٨ ملف ستايل** · وولا ملف بعد المضمّنة

   ⤷ يعني `tokens.css` اليوم **آخر واحد بالسلسلة**، فبيغلب إلمنتور
     وووكومرس والقالب **عند تساوي الأسبقية**. ولو انطفى المضمّن وهو
     مسجّل بأولوية ٥، بيصير **١٨ ملفاً بيدهسوه** والكسر بيطلع متفرّقاً
     وصعب التتبّع. [[important-beats-specificity]]

   **فالحل: نطبع الوسم بإيدنا على `wp_head` بأولوية متأخرة**، لأنّ
   الستايلات المسجّلة بتنطبع عند أولوية ٨، فأي رقم أكبر بيضمن إننا
   بعدهن كلهن · وهاد بيطابق مكان المضمّن الحالي بالضبط.

   ⚠️ والوسم المطبوع بالإيد **برّا شجرة التبعيات**، وهاد مقبول هون لأنّ
      **ولا ستايل عندنا بيعتمد على `luvit-tokens`** · هو الأساس لا التابع.
   ══════════════════════════════════════════════════════════════════════ */
add_action(
	'wp_head',
	function () {
		if ( is_admin() ) {
			return;
		}
		$name = luvit_css_file_name();

		/* 🔴 حارس ٣ · بلا ملف ما منطبع شي · والمضمّن بيغطّي */
		if ( '' === $name ) {
			return;
		}

		$up  = wp_upload_dir();
		$url = trailingslashit( $up['baseurl'] ) . 'luvit/' . $name;

		echo '<link rel="stylesheet" id="luvit-tokens-css" href="'
			. esc_url( $url ) . '" media="all">' . "\n";
	},
	999
);
