<?php
/**
 * ============================================================================
 * تحويل /shop على /products · سنيبت WPCode (نوع PHP · Run Everywhere)
 * ============================================================================
 * الدمج · ٣٠ آب ٢٠٢٦ · قرار ريّان: «ندمجهم بصفحة وحدة قوية.»
 *
 * ليش التحويل بالـPHP مش بـRank Math:
 *   الوجهة الباقية /products لازم تكون **صفحة عادية**، لأن أي صفحة تتعيّن
 *   shop page بإعدادات ووكومرس بينمسح محتواها ويتركّب مكانه أرشيف المنتجات.
 *   ومعناها إن /shop لازم تضل موجودة كصفحة ووكومرس الرسمية (بيستعملها
 *   «الرجوع للمتجر» وفتات الخبز) بس ما حدا يشوفها. التحويل هون بيخلي
 *   المنطق جنب سببه وبينحفظ بـgit، بدل ما يكون إعداداً مخفياً بلوحة بلجن.
 *
 * 🔴 ثلاثة استثناءات مقصودة · بلاها بينكسر شغل شغّال:
 *   ١ · الأدمن والـAJAX والـREST والكرون — التحويل للواجهة بس.
 *   ٢ · أي طلب معه باراميترات (?product_cat= · ?orderby= · ?add-to-cart=)
 *       بيعدّي بلا تحويل · تحويل أعمى بيقتل فلترة الفئات والإضافة للسلة.
 *   ٣ · باراميتر `luvit_raw=1` بيتخطّى التحويل · لازم للفحص وللمقارنة،
 *       وإلا بنفقد القدرة نشوف الأرشيف الأصلي.
 *
 * والتحويل **301** مش 302: القرار دائم، وبدنا محركات البحث تنقل الترتيب
 * للوجهة الوحدة بدل ما تضل تفهرس الاثنتين (وهاد كان بيصير فعلاً: الصفحتان
 * كانتا `index, follow` بوصفين شبه متطابقين).
 * ============================================================================
 */

add_action( 'template_redirect', function () {

	// ١ · الواجهة بس
	if ( is_admin() || wp_doing_ajax() || wp_doing_cron() ) {
		return;
	}
	if ( defined( 'REST_REQUEST' ) && REST_REQUEST ) {
		return;
	}

	// ٢ · مخرج الطوارئ للفحص
	if ( ! empty( $_GET['luvit_raw'] ) ) {
		return;
	}

	// ٣ · أي فلترة أو فرز أو إضافة للسلة بتعدّي زي ما هي
	$passthrough = array( 'product_cat', 'product_tag', 'orderby', 'add-to-cart', 'paged', 's', 'min_price', 'max_price' );
	foreach ( $passthrough as $key ) {
		if ( isset( $_GET[ $key ] ) ) {
			return;
		}
	}

	// ٤ · صفحة المتجر وحدها · مش صفحات المنتجات ولا الأرشيفات
	if ( ! function_exists( 'is_shop' ) || ! is_shop() ) {
		return;
	}
	if ( is_product() || is_product_category() || is_product_tag() ) {
		return;
	}

	// ٥ · الوجهة · من جدول ووردبريس مش نصاً مثبتاً بالكود
	$products = get_page_by_path( 'products' );
	if ( ! $products ) {
		return; // الصفحة مش موجودة · التحويل لرابط فاضي أسوأ من عدمه
	}

	/* 🔴 حارس الحلقة المغلقة · لو صار حدا عيّن /products نفسها «صفحة المتجر»
	   بإعدادات ووكومرس، بتصير is_shop() صحيحة عليها وبنحوّلها على حالها
	   للأبد. المقارنة بالمعرّف مش بالرابط، لأن الروابط بتختلف بالشرطة
	   الأخيرة وبالبروتوكول وبتخدع المقارنة النصية. */
	if ( (int) get_option( 'woocommerce_shop_page_id' ) === (int) $products->ID ) {
		return;
	}

	$target = get_permalink( $products );
	if ( ! $target ) {
		return;
	}

	wp_safe_redirect( $target, 301 );
	exit;

}, 5 );
