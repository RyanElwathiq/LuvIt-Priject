<?php
/**
 * ============================================================================
 * التوصيل مجاني مع أي روتين جاهز · سنيبت WPCode (PHP · Run Everywhere)
 * ============================================================================
 * قرار ريّان ٣٠ آب: «خلي التوصيل مجاني عالبكجات.»
 *
 * ── ليش هالقرار مهم تجارياً ────────────────────────────────────────────
 * الروتينات الثلاثة سعرها **مجموع قطعها بالضبط** (٦٠ · ٦١ · ٦١) · مقيس
 * مرتين من طريقين مستقلين. يعني الزبونة اللي بتحسب ما بتلاقي سبباً تشتري
 * البكج بدل ما تشتري القطع وحدة وحدة.
 *
 * والسبب إن استراتيجية العلامة **بتمنع الخصومات الأونلاين** عشان ما تضرب
 * أسعار الصيدليات. فالخصم مقفول، والشحن هو **الرافعة الوحيدة الناجية**:
 *   · بيكلّف ٢٫٥ دينار على سلة ٦٠ لـ٦١ · يعني ٤٫١٪
 *   · وخصم ١٠٪ بيكلّف ثلاثة أضعاف **وبيخلق تضارب أسعار**
 *   · والصيدلية ما بتشحن أصلاً · فما في تضارب
 *
 * ── ليش PHP مش «فئة شحن» ──────────────────────────────────────────────
 * فئة الشحن بووكومرس بتسعّر **الصنف**، مش الطلبية. يعني بكج + منتج مفرد
 * = ٠ + ٢٫٥ = دينارين ونص · والزبونة اللي اشترت روتيناً كاملاً بتدفع شحناً
 * لأنها زادت غسولاً.
 *
 * والقاعدة هون **على مستوى الطلبية**: بالسلة روتين جاهز؟ الشحن صفر.
 * وهاي بتنحكى بجملة وحدة على الصفحة، والفئة لأ.
 *
 * ⚠️ والثغرة مقبولة بقصد **على الروتينات وحدها**: الروتين ٤٧ لـ٧١ ديناراً،
 *    فمين بيضيفه عشان يوفّر دينارين ونص شحن يكون اشترى بسبعين.
 *    🔴 **وما عادت مقبولة على الثنائيات** (٢٤ لـ٣٧٫٥) · لهيك انتغيّر الشرط
 *       من الفئة لعدد القطع · ٥ أيلول ٢٠٢٦.
 *
 * 🔴 والتعرّف على البكج **بالفئة مش بالمعرّفات**. كتابة 203 و204 و205
 *    بالكود بتنكسر بصمت أول ما ينضاف روتين رابع، والصفحة بتقول «مجاني»
 *    والسلة بتحاسب. الفئة `packages` هي نفسها اللي بتصنّفهم بالمتجر.
 * ============================================================================
 */

add_filter( 'woocommerce_package_rates', function ( $rates, $package ) {

	if ( ! function_exists( 'WC' ) || empty( $package['contents'] ) ) {
		return $rates;
	}

	/* 🔴 **الشرط بينقرا من `luvit_pk_ship_free()` · سنيبت ٥٧٧.**
	   قرار ريّان ٥ أيلول ٢٠٢٦: الشحن المجاني **للروتينات من أربع قطع
	   وأكثر وبس** · الثنائيات بتدفع الشحن.

	   ⚠️ **والاحتياطي بيرجع للفئة، ما بيمنع.** لو سنيبت ٥٧٧ انطفى أو
	      انحذف، منع الشحن المجاني بيحاسب زبونة اشترت روتيناً كاملاً ·
	      وهاد أسوأ من إعطائه لثنائية. فالاحتياطي **بيعطي** وبيسجّل.
	      [[absent-setting-is-not-absent-feature]] */
	$has_rule = function_exists( 'luvit_pk_ship_free' );
	if ( ! $has_rule && function_exists( 'wc_get_logger' ) ) {
		wc_get_logger()->warning( 'luvit: luvit_pk_ship_free مفقودة · رجعنا لقاعدة الفئة', array( 'source' => 'luvit-shipping' ) );
	}

	$has_routine = false;
	foreach ( $package['contents'] as $item ) {
		$product_id = ! empty( $item['product_id'] ) ? (int) $item['product_id'] : 0;
		if ( ! $product_id ) {
			continue;
		}
		$free = $has_rule
			? luvit_pk_ship_free( $product_id )
			: has_term( 'packages', 'product_cat', $product_id );
		if ( $free ) {
			$has_routine = true;
			break;
		}
	}

	if ( ! $has_routine ) {
		return $rates;
	}

	foreach ( $rates as $rate ) {
		$rate->cost = 0;
		/* الضرائب ما انفتحت بالمشروع بعد · وهاد بيصفّرها لو انفتحت لاحقاً
		   وإلا بتضل ضريبة محسوبة على شحن صار مجانياً. */
		$rate->taxes = array_map( function () { return 0; }, (array) $rate->taxes );
		$rate->label = 'التوصيل · مجاني مع الروتين';
	}

	return $rates;

}, 10, 2 );
