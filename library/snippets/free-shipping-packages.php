add_filter( 'woocommerce_package_rates', function ( $rates, $package ) {

	if ( ! function_exists( 'WC' ) || empty( $package['contents'] ) ) {
		return $rates;
	}

	$has_routine = false;
	foreach ( $package['contents'] as $item ) {
		$product_id = ! empty( $item['product_id'] ) ? $item['product_id'] : 0;
		if ( $product_id && has_term( 'packages', 'product_cat', $product_id ) ) {
			$has_routine = true;
			break;
		}
	}

	if ( ! $has_routine ) {
		return $rates;
	}

	foreach ( $rates as $rate ) {
		$rate->cost = 0;
		/* الضرائب ما انفتحت بالمشروع بعد · وهاد بيصفّرها لو انفتحت لاحقاً
		   وإلا بتضل ضريبة محسوبة على شحن صار مجانياً. */
		$rate->taxes = array_map( function () { return 0; }, (array) $rate->taxes );
		$rate->label = 'التوصيل · مجاني مع الروتين';
	}

	return $rates;

}, 10, 2 );
