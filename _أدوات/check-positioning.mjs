#!/usr/bin/env node
/**
 * ============================================================================
 * بوابة الموضعة · check-positioning.mjs
 * ============================================================================
 *   node _أدوات/check-positioning.mjs
 *
 * ── 🔴 ليش انبنت ─────────────────────────────────────────────────────────
 * ريّان صحّحني **مرتين** بنفس الشي:
 *
 *   ٣٠ آب: «مش عارف شو قصتك مع المكوّنات إنها مكتوبة عالعلبة يا ابن الحلال ·
 *          أكيد بدها تنكتب عالعلبة · ألف مرة قلتلك روح لفوائد المكوّنات
 *          مش تذكرها.»
 *   ٢ أيلول: «غلط ينذكروا كأنها الميزة الأساسية عننا وإننا منتفاخر فيها ·
 *          هاي مصيبة لأنها بديهيات.»
 *
 * وبينهم رجعت أبني عليها. **تصحيح انقال مرتين ونُسي مرتين لازمه بوابة
 * لا ملاحظة.**
 *
 * ── الفرق اللي بتحرسه ────────────────────────────────────────────────────
 * كتابة المكوّنات ونِسَبها على العبوة **إلزام تنظيمي** عند كل علامة، فما
 * بتميّز حدا. والميزة الحقيقية بكلام ريّان:
 *   «منبني كل إشي مخصّص لحاجة العميل مش العكس، ومنكون معه أول بأول
 *    ومنرشده ومنوصيه.»
 *
 * 🔴 **النسبة برهان تحت الوعد · مش الوعد.**
 *    ممنوعة بـ: `<h1>` · `<h2>` · عنوان بطاقة · عنوان خطوة · شريط الوعود.
 *    ✅ مسموحة بـ: جدول · بادج على بطاقة منتج · متن مقال موضوعه المكوّن.
 * ============================================================================
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');

/* 🔴 المقالات اللي موضوعها المكوّن نفسه مستثناة · «والنسبة بتفرق» عنوان
   مشروع بمقال عن النياسيناميد. الاستثناء **بالملف** لا بالعبارة. */
const مستثنى = /journal[\/](223|a4)-/;

/* عبارات بتبيع الشفافية كميزة · مش أي ذكر للنِسَب */
const عبارات = [
  /نِسَب\s+مكتوب/, /نسب\s+مكتوب/, /مكتوبة\s+على\s+العبوة/, /مكتوب\s+عالعبوة/,
  /مكتوبة\s+عالعبوة/, /النِسَب\s+مكتوبة/, /مكوّنات\s+واضحة/, /مكونات\s+واضحة/,
  /نِسَب\s+واضحة/, /مش\s+سرّ/,
];

/* الأماكن اللي ممنوعة فيها · عنوان أو وعد */
const أماكن = [
  [/<h1[^>]*>([\s\S]*?)<\/h1>/g, 'عنوان h1'],
  [/<h2[^>]*>([\s\S]*?)<\/h2>/g, 'عنوان h2'],
  [/luvit-card__title[^>]*>([\s\S]*?)</g, 'عنوان بطاقة'],
  [/luvit-step__title[^>]*>([\s\S]*?)</g, 'عنوان خطوة'],
  [/luvit-promise__item[^>]*>([\s\S]*?)<\/span>/g, 'شريط الوعود'],
  [/luvit-section__sub[^>]*>([\s\S]*?)<\/p>/g, 'سطر تحت العنوان'],
];

const ملفات = [];
for (const d of ['library/sections', 'library/journal']) {
  const p = path.join(REPO, d);
  if (!fs.existsSync(p)) continue;
  for (const f of fs.readdirSync(p)) if (f.endsWith('.html')) ملفات.push(path.join(d, f));
}

const errs = [];
for (const rel of ملفات) {
  if (مستثنى.test(rel)) continue;
  /* 🔴 الملفات المعلَّمة أرشيفاً بتنتخطّى · وعلامتها **جوّاها** لا بقائمة
     هون، عشان اللي بيفتح الملف يعرف إنه ميت قبل ما ينسخ منه. */
  if (fs.readFileSync(path.join(REPO, rel), "utf8").includes("LUVIT-LEGACY")) continue;
  const html = fs.readFileSync(path.join(REPO, rel), 'utf8').replace(/<!--[\s\S]*?-->/g, ' ');
  for (const [re, مكان] of أماكن) {
    for (const m of html.matchAll(re)) {
      const نص = m[1].replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
      for (const ع of عبارات) {
        if (ع.test(نص)) {
          errs.push(rel.split(/[\/]/).pop() + ' · ' + مكان + ' · «' + نص.slice(0, 58) + '»');
          break;
        }
      }
    }
  }
}

if (errs.length) {
  console.error('🔴 النِسَب بمكان الوعد · وهي بديهية مش ميزة:');
  errs.forEach((e) => console.error('     ' + e));
  console.error('');
  console.error('     الميزة: مخصّص لحاجة الزبونة · ومنكون معها ومنرشدها.');
  console.error('     والنسبة **برهان تحت الوعد** · محلّها جدول أو بادج.');
  process.exit(1);
}
console.log('✅ الموضعة · ' + ملفات.length + ' ملفاً · ولا نسبة بمكان الوعد');
