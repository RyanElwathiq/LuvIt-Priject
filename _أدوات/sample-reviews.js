/**
 * ============================================================================
 * تقييمات عيّنة · sample-reviews.js
 * ============================================================================
 * ريّان ٢١ آب: «تقييمات المنتجات خليها موجودة لأنه حنجيب آراء من الانستا
 * وأماكن كثيرة، بس هسا حط أمور عشوائية عشان يبين الشكل مش أكثر.»
 *
 * 🔴 هاي **مش آراء زبونات**. ولا وحدة منها قالها إنسان.
 *    وهي أخطر نوع محتوى وهمي بالموقع، لأن السعر الوهمي بيضحك على حدا واحد
 *    وقت الإطلاق، أما الرأي الوهمي فبيقنع زبونة حقيقية تشتري.
 *
 * ## كيف بتنمسك قبل الإطلاق
 * كل وحدة إيميلها على `@luvit.invalid`. و`.invalid` نطاق محجوز بـRFC 2606
 * وما بيقدر ينوجد فعلياً، فما في احتمال تتلخبط مع رأي حقيقي.
 * بوابة الإطلاق (`verify-live-honesty.js`) بتسأل ووكومرس عنها وبتقفل لو لقيت.
 *
 * ## وليش الكلام محصور بالإحساس
 * ما في ولا رقم ولا وعد طبي ولا نتيجة. كلها ملمس ورائحة وشكل العبوة، عشان
 * حتى لو وحدة منها انفلتت لبعد الإطلاق بالغلط، ما بتكون وعدت حدا بإشي.
 * ============================================================================
 */

const PRODUCTS = {
  203: 'بكج الروتين الأساسي',
  204: 'بكج البشرة الدهنية',
  205: 'بكج البشرة الجافة',
  201: 'منظف هيدرا اللطيف',
  191: 'سيروم فيتامين سي',
  202: 'تونر الترطيب العميق',
};

/* الأسماء أردنية عادية عشان الشكل يطلع طبيعي · والإيميل هو العلامة */
const R = [
  [203, 5, 'ريم',   'العبوات وصلت مرتبة وكل وحدة مكتوب عليها ترتيبها. أول مرة بعرف شو بحط قبل شو.'],
  [203, 4, 'دانا',  'الملمس خفيف وما بضل لزج. بحب إنه الرائحة هادية مش قوية.'],
  [203, 5, 'لينا',  'البكج مرتب وسهل، وما بحتاج أفكر كل ليلة شو الخطوة الجاية.'],
  [204, 5, 'هبة',   'الإحساس بعده منعش والبشرة ما بتشد. هاد اللي كنت بدور عليه.'],
  [204, 4, 'سلمى',  'الكمية كافية والعبوة عملية. التوزيع عالوجه بينسحب بسرعة.'],
  [204, 5, 'نور',   'خفيف ومرتب، وما بيترك طبقة عالوجه.'],
  [205, 5, 'رنا',   'الترطيب محسوس والملمس دسم بس مش ثقيل. مناسب لليل.'],
  [205, 5, 'أمل',   'العبوة كبيرة والرائحة لطيفة وما فيها كحول قوي.'],
  [205, 4, 'ميس',   'حلو بالشتا. بالصيف بستعمل كمية أقل وبكفي.'],
  [201, 5, 'ديمة',  'بينظف بلا ما يشد الوجه بعد الغسيل، وهاي أهم إشي عندي.'],
  [201, 4, 'زينة',  'الرغوة قليلة بس بتكفي، والكمية اللي بتنحط صغيرة.'],
  [191, 5, 'ياسمين','الملمس مائي وبينشف بسرعة، وبقدر أحط المرطب فوقه على طول.'],
  [191, 4, 'شهد',   'القطارة مضبوطة وبتطلع الكمية المناسبة بلا تبذير.'],
  [202, 5, 'ولاء',  'بحطه بقطنة وبحس الوجه نظيف ومرتاح بعده.'],
  [202, 4, 'رغد',   'الرائحة خفيفة والعبوة سهلة بالاستعمال اليومي.'],
];

/* تواريخ موزّعة على الشهرين الماضيين · التوزيع جزء من الشكل، والبوابة
   بتشيلهم كلهم قبل الإطلاق فما في تاريخ منهم بيوصل زبونة حقيقية */
const BASE = new Date('2026-06-20T09:00:00');
const out = R.map(([id, rating, name, text], i) => {
  const d = new Date(BASE.getTime() + i * 4 * 24 * 3600 * 1000 + (i % 5) * 3600 * 1000);
  return {
    product_id: id,
    review: text,
    reviewer: name,
    reviewer_email: 'sample' + String(i + 1).padStart(2, '0') + '@luvit.invalid',
    rating: rating,
    status: 'approved',
    date_created: d.toISOString().slice(0, 19),
  };
});

/* فحص قبل الكتابة: ولا شرطة طويلة، ولا رقم، ولا وعد */
const bad = [];
for (const r of out) {
  if (/—/.test(r.review)) bad.push('شرطة طويلة: ' + r.reviewer);
  if (/[0-9٠-٩]/.test(r.review)) bad.push('رقم بالنص: ' + r.reviewer);
  if (/خلال\s|أسبوع|شهر|اختف|شفي|علاج|نتيجة مضمونة/.test(r.review)) bad.push('وعد/مدة: ' + r.reviewer);
  if (!/@luvit\.invalid$/.test(r.reviewer_email)) bad.push('إيميل بلا علامة: ' + r.reviewer);
}
if (bad.length) { console.error('🔴 ' + bad.join('\n🔴 ')); process.exit(1); }

require('fs').writeFileSync(
  __dirname + '/../library/sample-reviews.json',
  JSON.stringify(out, null, 2),
  'utf8'
);
console.log('✅ ' + out.length + ' تقييم عيّنة · ' + Object.keys(PRODUCTS).length + ' منتج · كلها @luvit.invalid');
