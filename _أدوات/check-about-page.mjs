#!/usr/bin/env node
/**
 * ============================================================================
 * بوابة صفحة «من نحن» · check-about-page.mjs
 * ============================================================================
 *   node _أدوات/check-about-page.mjs
 *
 * ── 🔴 ليش انبنت ─────────────────────────────────────────────────────────
 * الصفحة ضلّت **أشهر** بتقول «أربع روتينات · دهنية وجافة ومختلطة وحساسة»
 * و«منبدأ من نوع البشرة» بعد ما تحوّل النموذج للهدف · وولا فحص شافها،
 * لأنها **مكتوبة بالإيد** وما بتمرّ بأي مولّد.
 *
 * وأسوأ: تعليق جوّاها كان بيقول «✅ كل البطاقات مثبتة» فوق بطاقة محتواها
 * غلط · **فالتوثيق نفسه كان بيحرس الغلط**.
 *
 * ⤷ الفحص هون بيقارن الصفحة بـ`routines.mjs` (مصدر الروتينات الوحيد)
 *   وبصفحات الموقع التانية، عشان ما تتناقض معهن.
 * ============================================================================
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROUTINES, عدد } from './routines.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');
const F = path.join(REPO, 'library', 'sections', 'a1-about.html');
const html = fs.readFileSync(F, 'utf8');
const errs = [];

/* النصّ الظاهر · بلا تعليقات ولا وسوم */
const نص = html.replace(/<!--[\s\S]*?-->/g, ' ').replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ');

/* ── ١ · نموذج نوع البشرة انتهى ─────────────────────────────────── */
const ممنوع = [
  ['روتين لكل نوع بشرة', 'الروتينات صارت بالهدف'],
  ['دهنية وجافة ومختلطة وحساسة', 'هاي أسماء أنواع بشرة لا أسماء روتينات'],
  ['منبدأ من نوع البشرة', 'المسار بيبدأ من الهدف'],
];
for (const [ص, ليش] of ممنوع) if (نص.includes(ص)) errs.push('عبارة منتهية: «' + ص + '» · ' + ليش);

/* ── ٢ · العدد ────────────────────────────────────────────────────── */
const عربي = { 'تلات': 3, 'ثلاث': 3, 'أربع': 4, 'خمس': 5, 'ست': 6 };
for (const m of نص.matchAll(/(تلات|ثلاث|أربع|خمس|ست)ة?\s+روتينات/g)) {
  if (عربي[m[1]] !== عدد) errs.push('عدد الروتينات: «' + m[0] + '» والصح ' + عدد);
}

/* ── ٣ · أي اسم روتين مذكور لازم يكون من المصدر ──────────────────── */
const أسماء = ROUTINES.map((r) => r.gate.label);
const مذكور = أسماء.filter((a) => نص.includes(a));
if (مذكور.length && مذكور.length !== أسماء.length) {
  errs.push('ذكرت ' + مذكور.length + ' روتينات من ' + أسماء.length +
    ' · ناقص: ' + أسماء.filter((a) => !مذكور.includes(a)).join(' · '));
}

/* ── ٤ · صبح/مسا · الموقع بيقول العكس ─────────────────────────────
   🔴 صفحات الروتينات الأربعة بتقول «نفس الترتيب صباحاً ومساءً» ومعها
      تعليق إن الروتين **ما انقسم**. أي وعد بترتيبين هون تناقض حيّ. */
if (/ترتيب\s+واضح\s+للصبح\s+وللمسا|روتين\s+صباحي\s+وروتين\s+مسائي/.test(نص)) {
  errs.push('بيوعد بترتيب صبح ومسا منفصلين · وصفحات الروتينات بتقول «نفس الترتيب صباحاً ومساءً»');
}

/* ── ٥ · بصمات صفحة AI · مقيسة ──────────────────────────────────── */
const سكاشن = (html.match(/<section\b/g) || []).length;
const eyebrows = (html.match(/luvit-section__eyebrow/g) || []).length;
const سقف = Math.ceil(سكاشن / 3);
if (eyebrows > سقف) errs.push('eyebrow: ' + eyebrows + ' والسقف ' + سقف + ' لـ' + سكاشن + ' سكاشن');
const صور = (html.match(/<img\b/g) || []).length;
if (!صور) errs.push('ولا صورة بالصفحة');

/* ── ٦ · الشرطة الطويلة وتوازن الوسوم ───────────────────────────── */
if (/—/.test(html)) errs.push('شرطة طويلة');
/* ⚠️ النمط بلا `[ >]` بقصد · الهروب بيتاكل بالنقل عبر الشِل وبيصير
   محرف backspace حرفي، فالعدّ بيطلع 0/27 وبتبيّن الوسوم «مش متوازنة»
   وهي متوازنة · إنذار كاذب من البوابة نفسها. `[ >/]` بتكفي. */
for (const tag of ['div', 'section', 'figure', 'article', 'p']) {
  const o = (html.match(new RegExp('<' + tag + '[ >]', 'g')) || []).length;
  const c = (html.match(new RegExp('</' + tag + '>', 'g')) || []).length;
  if (o !== c) errs.push('وسوم مش متوازنة: ' + tag + ' ' + o + '/' + c);
}

if (errs.length) {
  console.error('🔴 a1-about.html');
  errs.forEach((e) => console.error('     ' + e));
  process.exit(1);
}
console.log('✅ a1-about.html · ' + سكاشن + ' سكاشن · ' + eyebrows + '/' + سقف +
  ' eyebrow · ' + صور + ' صورة · ' + عدد + ' روتينات مطابقة للمصدر');
