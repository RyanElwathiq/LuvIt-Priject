#!/usr/bin/env node
/**
 * ============================================================================
 * فحص سنيبت PHP قبل رفعه · lint-php-snippet.js
 * ============================================================================
 *   node _أدوات/lint-php-snippet.js library/journal.php
 *
 * ما في PHP مركّب محلياً، فما بنقدر نشغّل `php -l`. وهاد بديل بيمسك الفئة
 * اللي بتوقعنا فيها فعلاً: **أخطاء التركيب اللي بتصير من التعديل الآلي**.
 *
 * 🔴 ليش انكتب: عدّلنا الملف بالفهرس (`L.splice(...)`) وانبلع `$out` من
 *    سطر، فصار `.= '</div>';` لحاله. الفاحص اللي كان عندنا فحص توازن
 *    الأقواس والاقتباسات و**مرّها**، وWPCode رفض التفعيل برسالة
 *    `syntax error, unexpected token ".="`.
 *
 *    والرسالة ما كانت ظاهرة بالصفحة · هي برد أجاكس، وما بتنشاف إلا لما
 *    تعترض الاستدعاء. عشان هيك الفحص لازم يصير **قبل** الرفع.
 *
 * ⚠️ وهاد فحص أنماط مش محلّل لغة · بيمسك الشائع مش كل شي. النجاح هون
 *    معناه «ما لقيت نمطاً معروفاً»، مش «الكود سليم».
 * ============================================================================
 */

const fs = require('fs');

const file = process.argv[2];
if (!file) {
  console.error('استعمال: node _أدوات/lint-php-snippet.js <ملف.php>');
  process.exit(2);
}
if (!fs.existsSync(file)) {
  console.error('🔴 مش موجود: ' + file);
  process.exit(2);
}

const src = fs.readFileSync(file, 'utf8');
const issues = [];

/* شيل التعليقات · التعليقات العربية فيها أقواس واقتباسات بتكذّب أي عدّ */
function stripComments(s) {
  return s
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (m, p) => p + ' '.repeat(m.length - p.length));
}
const code = stripComments(src);
const lines = code.split('\n');
const rawLines = src.split('\n');

/* ── ١ · عامل بلا معامل يسار · هاي اللي كسرتنا ─────────────────────── */
lines.forEach((l, i) => {
  const t = l.trim();
  if (!t) return;
  /* سطر بيبدأ بعامل تعيين أو ربط · يعني اللي قبله انبلع */
  /* ⚠️ `=>` **مستثنى** · هو فاصل مفتاح/قيمة بالمصفوفات، وسطر بيبدأ فيه
     تركيب سليم وشائع بمصفوفة مفاتيحها طويلة. بلا الاستثناء رجّع الفاحص
     تلات إنذارات كاذبة على ملف صحيح · ونفس الملف تحت بيحذّر إن فاحصاً
     بيصرخ على السليم بينتجاهل. */
  if (/^(\.=|\+=|-=|\*=|\/=|=[^=>])/.test(t)) {
    issues.push('سطر ' + (i + 1) + ' · عامل بلا متغيّر قبله → ' + rawLines[i].trim().slice(0, 70));
  }
  /* ⚠️ كان هون فحص «ربط معلّق» بيرفض أي سطر بيبدأ بنقطة إذا اللي قبله ما
     بينتهي بعامل. وطلع **إنذاراً كاذباً بالجملة**: الربط على أسطر متعددة
     تركيب PHP سليم وشائع، وأي سطر بينتهي بسلسلة نصية بينتهي باقتباس
     فبيتّهم اللي بعده.

     الفحص رجّع ٩ إنذارات كلها كاذبة على ملف صحيح · وفاحص بيصرخ على السليم
     بينتجاهل، وبعدها بيمرّ الغلط لأن حدا وقف يقرا مخرجاته.

     القاعدة اللي فوق (عامل بلا متغيّر قبله) هي اللي مسكت الباغ الحقيقي،
     وهي بتكفي. */
});

/* ── ٢ · توازن ─────────────────────────────────────────────────────── */
/* شيل السلاسل النصية كمان قبل عدّ الأقواس */
const noStr = code.replace(/'(?:\\.|[^'\\])*'/g, "''").replace(/"(?:\\.|[^"\\])*"/g, '""');
for (const [a, b, name] of [['{', '}', 'أقواس معقوفة'], ['(', ')', 'أقواس دائرية'], ['[', ']', 'أقواس مربعة']]) {
  const na = noStr.split(a).length - 1;
  const nb = noStr.split(b).length - 1;
  if (na !== nb) issues.push(name + ' غير متوازنة: ' + na + ' / ' + nb);
}

/* ── ٣ · اقتباس مفتوح · بتتبّع الحالة عبر الملف كله ─────────────────
   ⚠️ النسخة الأولى فحصت **كل سطر لحاله** وطلّعت إنذارين كاذبين على
   `email-rtl.php` وهو شغّال على الموقع من ساعات: سلسلة PHP بتمتد على
   أسطر (`$css .= '` ... أسطر CSS ... `';`) تركيب سليم تماماً، والسطر
   الأول فيها بينتهي باقتباس مفتوح **عن قصد**.

   فالسؤال مش «هل السطر متوازن» · السؤال «هل الملف بينتهي وهو جوّا سلسلة».
   والتتبّع بيمسك الاقتباس اللي فعلاً ما انسكّر. */
let inSingle = false, openedAt = 0;
lines.forEach((l, i) => {
  let esc = false;
  for (const ch of l) {
    if (esc) { esc = false; continue; }
    if (ch === '\\') { esc = true; continue; }
    if (ch === "'") {
      if (!inSingle) { inSingle = true; openedAt = i + 1; } else { inSingle = false; }
    }
  }
});
if (inSingle) {
  issues.push('اقتباس مفرد مفتوح من سطر ' + openedAt + ' وما انسكّر لآخر الملف → ' +
    (rawLines[openedAt - 1] || '').trim().slice(0, 60));
}

/* ── ٤ · وسم PHP ───────────────────────────────────────────────────── */
if (/\?>/.test(code)) issues.push('فيه وسم إغلاق ?> · WPCode ما بيحتاجه');

/* ── ٥ · فاصلة منقوطة ناقصة قبل سطر بيبدأ بمتغيّر ─────────────────── */
lines.forEach((l, i) => {
  const t = l.trim(), prev = (lines[i - 1] || '').trim();
  if (!t || !prev) return;
  if (/^\$\w+\s*(\.?=|\[)/.test(t) && /[^;{}:,([]$/.test(prev) && !/^(if|else|foreach|while|for|function|return|})/.test(prev)) {
    issues.push('سطر ' + (i + 1) + ' · يمكن فاصلة منقوطة ناقصة بالسطر اللي قبله → ' + prev.slice(-50));
  }
});

console.log('الملف   : ' + file);
console.log('الأسطر  : ' + lines.length);
console.log('الدوال  : ' + ([...code.matchAll(/^function ([a-z_]+)\s*\(/gm)].map((m) => m[1]).join(' · ') || 'ولا وحدة'));
console.log('---');

if (issues.length) {
  issues.forEach((x) => console.error('🔴 ' + x));
  console.error('---');
  console.error('🔴 ' + issues.length + ' مشكلة · ما ترفعه');
  process.exit(1);
}
console.log('✅ ما لقيت نمطاً معروفاً · وهاد مش إثبات سلامة كاملة');
