#!/usr/bin/env node
/**
 * ============================================================================
 * فحص مقالات المدوّنة · check-journal-posts.mjs
 * ============================================================================
 *   node _أدوات/check-journal-posts.mjs
 *
 * بيفحص ملفات `library/journal/*.html` قبل ما تنرفع.
 *
 * ── 🔴 والفحص الأهم: النِسَب ───────────────────────────────────────────
 * أي رقم بصيغة نسبة مذكور بالمقال **لازم يكون موجوداً بالكتالوج الرسمي**
 * (`_خطة/بيانات-المنتجات-الرسمية.json`). ولا رقم بينكتب من الراس.
 *
 * وهاد مش فحص نظري · المقال القديم عن النياسيناميد كان بيقول «بمنتجاتنا
 * النسبة 2%» و**هاد غلط**: النياسيناميد عنا بخمس نِسَب (0.5 · 0.8 · 2 ·
 * 2 · 10). الجملة كانت بتقرا كحقيقة وهي مش دقيقة، وضلّت منشورة.
 *
 * ⚠️ والفحص بيقبل كمان النِسَب اللي بالكتالوج **بأي منتج**، مش بس بالمنتج
 *    المذكور · لأن المقال ممكن يقارن بين منتجات. يعني هو **شبكة أمان
 *    ضد الاختراع**، مش تدقيقاً على الربط الصح · وهاد بينقرا بالعين.
 * ============================================================================
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { منتجات, فيها, عدد_المفردات, نِسَب_معروفة } from './ingredient-map.mjs';
import { ROUTINES } from './routines.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');
const DIR = path.join(REPO, 'library', 'journal');

const cat = JSON.parse(fs.readFileSync(path.join(REPO, '_خطة', 'بيانات-المنتجات-الرسمية.json'), 'utf8'));

/* كل نسبة معروفة بالكتالوج · مخزّنة كنصّ منظّف («0.5%» و«5% + 0.5%») */
const KNOWN = new Set();
for (const p of cat.منتجات) {
  for (const a of p.actives || []) {
    for (const m of String(a.pct).matchAll(/(\d+(?:\.\d+)?)\s*%/g)) KNOWN.add(m[1]);
  }
}

/* الصفحات الحيّة · أي رابط داخلي غيرها بيوقف الفحص.
   🔴 `/routines/oily` و`/routines/dry` و`/routines/combination` **انشالوا
      ٣٠ آب** وبيرجّعوا 404 · والمقال ٢٢٥ كان لساه بيربط على الأول. */
const LIVE = new Set([
  '/', '/products', '/cart', '/checkout', '/my-account', '/track', '/routines',
  '/quiz', '/shipping', '/faq', '/journal', '/about', '/contact', '/returns',
  '/privacy', '/terms',
  /* 🔴 مشتقّة · كانت تلات مسارات مكتوبة بالإيد، فأول رابط لروتين
     رابع بمقال وقّف البوابة **وهو رابط سليم وحيّ**. */
  ...ROUTINES.map((r) => '/routines/' + r.key),
  
]);

const files = fs.readdirSync(DIR).filter((f) => f.endsWith('.html')).sort();
let bad = 0;

for (const f of files) {
  const html = fs.readFileSync(path.join(DIR, f), 'utf8');
  const errs = [];

  /* ١ · تعليقات جوتنبرج متوازنة · كل فتح إله إغلاق بنفس الاسم */
  const opens = [...html.matchAll(/<!--\s+wp:([a-z-]+)(?:\s+\{[^}]*\})?\s+-->/g)].map((m) => m[1]);
  const closes = [...html.matchAll(/<!--\s+\/wp:([a-z-]+)\s+-->/g)].map((m) => m[1]);
  const tally = {};
  opens.forEach((x) => { tally[x] = (tally[x] || 0) + 1; });
  closes.forEach((x) => { tally[x] = (tally[x] || 0) - 1; });
  for (const [k, v] of Object.entries(tally)) if (v !== 0) errs.push(`كتلة wp:${k} غير متوازنة (${v > 0 ? 'ناقصها إغلاق' : 'إغلاق زيادة'})`);

  /* ٢ · وسوم HTML متوازنة */
  for (const t of ['p', 'h2', 'h3', 'ul', 'ol', 'li', 'strong', 'a', 'blockquote', 'table', 'tr', 'td', 'th', 'thead', 'tbody', 'figure']) {
    const o = (html.match(new RegExp('<' + t + '(?=[\\s>])', 'g')) || []).length;
    const c = (html.match(new RegExp('</' + t + '>', 'g')) || []).length;
    if (o !== c) errs.push(`<${t}> ${o}/${c}`);
  }

  /* ٣ · الشرطة الطويلة ممنوعة */
  if (html.includes('—')) errs.push('شرطة طويلة');

  /* ٣ب · نجمات ماركداون · بتنطبع نصاً حرفياً بالمقال
     🔴 كتبت `**كل**` بمقال الشهادات ظاناً إنها بتغمّق · وووردبريس
        بيطبعها نجمات. الماركب هون HTML لا ماركداون · التغميق `<strong>`. */
  const md = html.replace(/<!--[\s\S]*?-->/g, '').match(/\*\*[^*\n]+\*\*/g);
  if (md) errs.push('نجمات ماركداون: ' + md.slice(0, 3).join(' · '));

  /* ٤ · النِسَب · شبكة الأمان ضد الاختراع
     🔴 المصدر كان **الكتالوج وحده** (٩ منتجات)، والمتجر فيه ١٢ مفرداً.
        فالبوابة كانت **بترفض الحقيقة**: ٣٪ ترانيكساميك موجودة بووكومرس
        وما إلها ذكر بالكتالوج، فتصحيح صحيح بيوقف بـ«نسبة مخترعة».
        ⚠️ وبوابة مصدرها أضعف من مصدر الكاتب بتغلط **بالاتجاهين**:
           بتمرّر الغلط وبترفض الصح.
     ⤷ المصدر صار `نِسَب_معروفة` من `ingredient-map.mjs` · كتالوج + ووكومرس. */
  const used = [...new Set([...html.matchAll(/(\d+(?:\.\d+)?)\s*%/g)].map((m) => m[1]))];
  const invented = used.filter((x) => !نِسَب_معروفة.has(x));
  if (invented.length) errs.push('نِسَب مش بأي مصدر: ' + invented.join(' · '));

/* 🔴 توحيد اسم المنتج قبل أي مقارنة · الكوبي بيزيّن الأسماء.
   «تونر «تضييق المسامات»» بالمقال و«تونر تضييق المسامات» بووكومرس —
   **نفس المنتج**، والبوابة صرخت «اسم مش موجود» **وهو موجود بالجدول**.
   ⚠️ وبنفس اللحظة قالت «ناقص من الجدول» على نفس المنتج · إنذاران
      متناقضان من سطر واحد، وهاد بالضبط اللي بيخلّي حدا يطفّي الأداة. */
const اسم_موحّد = (s) => String(s)
  .replace(/[«»""'']/g, '')
  .replace(/\s+/g, ' ')
  .trim();

  /* ٤ب · 🔴 **الزوج**: منتج + نسبة · مش الرقم لحاله
     ══════════════════════════════════════════════════════════════════
     الفحص فوق بيسأل «هل الرقم موجود بالكتالوج؟» وبس. يعني
     «غسول البشرة الدهنية · 10%» **بتمرّ** لأن `10` موجودة بمكان تاني
     (بسيروم تضييق المسامات)، مع إن الغسول نسبته **0.5%**.
     ⤷ أي صف جدول بيقرن اسم منتج بنسبة بينفحص **كزوج** من المصدر
       المدموج (كتالوج + ووكومرس)، لا من قائمة أرقام سايبة. */
  for (const row of html.matchAll(/<tr><td>([^<]+)<\/td><td>(?:<strong>)?([\d.]+)\s*%/g)) {
    const اسم = row[1].trim();
    const نسبة = row[2];
    const منتج = منتجات.find((p) => اسم_موحّد(p.name) === اسم_موحّد(اسم));
    if (!منتج) { errs.push('صف جدول باسم منتج مش موجود: «' + اسم + '»'); continue; }
    if (!منتج.actives.some((a) => String(a.pct).replace(/%/g, '').trim() === نسبة)) {
      errs.push('زوج غلط: «' + اسم + '» ما فيه ' + نسبة + '% · اللي فيه: ' +
        منتج.actives.map((a) => a.pct + '% ' + a.name).join(' · '));
    }
  }

  /* ٤ج · 🔴 **العدّ** · وهاي الفئة اللي شحنت غلط **مرتين**
     ══════════════════════════════════════════════════════════════════
     «النياسيناميد عنا مكتوب بخمس منتجات» · والحقيقة **سبعة من ١٢**.
     «البانثينول بسبعة من تسعة» · والحقيقة **تمانية من ١٢**.
     السبب: انكتبوا من الكتالوج (٩ منتجات) والمتجر فيه ١٢.

     🔴 والبوابة القديمة ما كان فيها **ولا فحص** لعبارات العدّ · مرقوا
        كلاهما وهي بتقول «✅ كل النِسَب من الكتالوج».

     المادة بتنعرف من **اسم الملف** لا من النص · أوثق وأبسط. */
  const مادة_الملف = { niacinamide: 'نياسيناميد', panthenol: 'بانثينول',
                       'hyaluronic': 'هيالورونيك', 'vitamin-c': 'فيتامين سي' };
  const مفتاح = Object.keys(مادة_الملف).find((k) => f.includes(k));
  if (مفتاح) {
    const مادة = مادة_الملف[مفتاح];
    const حقيقة = فيها(مادة);
    const عربي = { 'اثنين': 2, 'تلات': 3, 'ثلاث': 3, 'أربع': 4, 'خمس': 5, 'ست': 6,
                   'سبع': 7, 'سبعة': 7, 'تمان': 8, 'تمانية': 8, 'تسع': 9, 'عشر': 10 };
    const نص = html.replace(/<[^>]+>/g, ' ');

    /* «بـ<عدد> منتجات» */
    for (const m of نص.matchAll(/بـ?\s*(اثنين|تلات|ثلاث|أربع|خمس|ست|سبعة|سبع|تمانية|تمان|تسع|عشر)ة?\s+منتجات/g)) {
      const قيل = عربي[m[1]];
      if (قيل !== حقيقة.length) {
        errs.push('عدّ غلط: «' + m[0].trim() + '» · ' + مادة + ' بـ' +
          حقيقة.length + ' من ' + عدد_المفردات + ' منتجاً مفرداً');
      }
    }
    /* «<عدد> من <عدد>» */
    for (const m of نص.matchAll(/(اثنين|تلات|ثلاث|أربع|خمس|ست|سبعة|سبع|تمانية|تمان|تسع|عشر)ة?\s+من\s+(اثنين|تلات|ثلاث|أربع|خمس|ست|سبعة|سبع|تمانية|تمان|تسع|عشر|تسعة)ة?/g)) {
      const بسط = عربي[m[1]], مقام = عربي[m[2]];
      if (بسط !== حقيقة.length || مقام !== عدد_المفردات) {
        errs.push('عدّ غلط: «' + m[0].trim() + '» · الصح ' +
          حقيقة.length + ' من ' + عدد_المفردات);
      }
    }
    /* وكل منتج فيه المادة لازم يكون بالجدول · النقص كذب بالحذف */
    if (/<table>/.test(html)) {
      const بالجدول = [...html.matchAll(/<tr><td>([^<]+)<\/td>/g)].map((x) => اسم_موحّد(x[1]));
      const ناقص = حقيقة.filter((h) => !بالجدول.includes(اسم_موحّد(h.منتج)));
      if (ناقص.length && بالجدول.length) {
        errs.push('ناقص من جدول ' + مادة + ': ' + ناقص.map((n) => n.منتج + ' (' + n.نسبة + '%)').join(' · '));
      }
    }
  }

  /* ٤هـ · 🔴 **النطاق المصرَّح** · وبينفحص هو كمان
     ══════════════════════════════════════════════════════════════════
     في مقال واحد مقامه **٩ بحق** · جدول الشهادات، لأن التلاتة الجداد
     (سنتيلا L103 · ألفا أربوتين L119 · واقي الشمس L112) ما إلهم بيانات
     شهادات **بولا مصدر**. فالأرقام صح والمقام هو اللي بيوهم.

     ⤷ الحل مش تخفيف البوابة · الحل إن المقال **يصرّح بنطاقه** بعلامة
       آلية، والبوابة تتأكد إن التصريح **مطابق للواقع**:
           <!-- luvit-scope: certs 9/12 -->
       ٩ = عدد المنتجات اللي عندها بيانات شهادات فعلاً
       ١٢ = عدد المفردات الحيّة
     ⚠️ وبلا الفحص التاني، التصريح بيصير باب خلفي: أي رقم غلط بينجا
        بكتابة نطاق يوافقه. */
  const نطاق = html.match(/<!--\s*luvit-scope:\s*(\w+)\s+(\d+)\s*\/\s*(\d+)\s*-->/);
  let مقام_مسموح = [عدد_المفردات];
  if (نطاق) {
    const [, نوع, بسط, كل] = نطاق;
    if (Number(كل) !== عدد_المفردات) {
      errs.push('نطاق مصرَّح مقامه ' + كل + ' والمفردات الحيّة ' + عدد_المفردات);
    }
    if (نوع === 'certs') {
      const عندها = منتجات.filter((p) => (p.certs || []).length).length;
      if (Number(بسط) !== عندها) {
        errs.push('نطاق الشهادات مصرَّح ' + بسط + ' والواقع ' + عندها + ' منتجاً عندهم شهادات');
      }
    }
    مقام_مسموح.push(Number(بسط));
  }

  /* ٤د · 🔴 **المقام** · بكل مقال لا بمقالات المكوّنات وحدها
     ══════════════════════════════════════════════════════════════════
     كل عبارة «X من Y» بتعدّ منتجات، مقامها لازم يكون **عدد المفردات
     الحيّة**. والمقالات انكتبت كلها من الكتالوج الرسمي (٩ منتجات)
     والمتجر فيه ١٢، فالتسعة ظهرت **مقاماً بأربع مقالات**:
       «9 من 9» · «2 من 9» · «سبعة من تسعة» · «منتجان فيهم أحماض»
     ⚠️ والفحص اللي فوق (٤ج) كان بيشتغل على المقالات اللي اسم الملف
        فيه اسم مكوّن بس · فالباقي مرقوا. */
  {
    const نص2 = html.replace(/<!--[\s\S]*?-->/g, ' ').replace(/<[^>]+>/g, ' ');
    const رقم = { 'اثنين': 2, 'تلات': 3, 'ثلاث': 3, 'أربع': 4, 'خمس': 5, 'ست': 6,
                  'سبعة': 7, 'سبع': 7, 'تمانية': 8, 'تمان': 8, 'تسعة': 9, 'تسع': 9,
                  'عشرة': 10, 'عشر': 10, 'اثنعش': 12 };
    const كلمات = Object.keys(رقم).join('|');
    /* بالحروف · «سبعة من تسعة» */
    for (const m of نص2.matchAll(new RegExp('(' + كلمات + ')ة?\s+من\s+(' + كلمات + ')ة?', 'g'))) {
      if (!مقام_مسموح.includes(رقم[m[2]])) {
        errs.push('مقام غلط: «' + m[0].trim() + '» · المفردات الحيّة ' + عدد_المفردات);
      }
    }
    /* بالأرقام · «9 من 9» */
    for (const m of نص2.matchAll(/(\d+)\s+من\s+(\d+)/g)) {
      if (!مقام_مسموح.includes(Number(m[2]))) {
        errs.push('مقام غلط: «' + m[0].trim() + '» · المفردات الحيّة ' + عدد_المفردات);
      }
    }
  }

  /* ٥ · الروابط الداخلية */
  for (const m of html.matchAll(/href="([^"]+)"/g)) {
    const h = m[1];
    if (h === '#') { errs.push('رابط ميت href="#"'); continue; }
    if (h.startsWith('http') || h.startsWith('#')) continue;
    const p = h.split('#')[0].replace(/\/$/, '') || '/';
    if (!LIVE.has(p)) errs.push('رابط مش حيّ: ' + h);
  }

  /* ٦ · وعود ممنوعة · صياغات بتوعد بنتيجة أو بمدة
     ─────────────────────────────────────────────────────────────────
     🔴 النسخة الأولى من هالفحص كانت **ميتة ومرّت بصمت**:
        كتبتها بحدود كلمات · `/\\bبيعالج\\b/` · و`\\b` بجافاسكربت
        معرَّفة على `[A-Za-z0-9_]`، فما بتلاقي حدّاً حوالين حرف عربي
        و**التعبير ما بيطابق ولا مرة**.
        مثبت: `/\\bبيعالج\\b/.test('بيعالج الحبوب')` بترجّع `false`.
     ⤷ يعني الفاحص كان بيقول «ولا وعد» وهو ما فحص ولا كلمة · وهاد أخطر
       من ولا فاحص، لأنه بيعطي ثقة كاذبة.

     ⚠️ والنفي لازم ينفهم كمان: «ما رح نقولك إنه **بيعالج** الحبوب»
        هي **عكس** الوعد، وهي بالضبط الصياغة اللي بدنا نشجّعها. فالفحص
        بيتجاهل المطابقة لو قبلها نفي بمدى قريب. */
  const PROMISE = [
    /خلال\s+(أسبوع|أسبوعين|شهر|\d+)/g,
    /بيعالج/g, /بيشفي/g, /بيقضي على/g, /بينهي/g,
    /مضمون/g, /نتيجة مضمونة/g,
    /100\s*٪?\s*(فعّال|مضمون)/g,
  ];
  /* صيغ النفي · «ما رح نقولك» · «ولا إنه» · «مش» · «ما بـ» */
  const NEG = /(ما رح نقول|ولا إن|ولا إنه|ما منقول|مش |ما بي|ولا بي|ما منوعد)/;
  const plain = html.replace(/<[^>]+>/g, ' ');
  for (const re of PROMISE) {
    let m;
    while ((m = re.exec(plain))) {
      const before = plain.slice(Math.max(0, m.index - 60), m.index);
      if (NEG.test(before)) continue;   /* منفيّة · وهاي الصياغة المطلوبة */
      errs.push('صيغة وعد: «' + plain.slice(Math.max(0, m.index - 24), m.index + m[0].length + 12).replace(/\s+/g, ' ').trim() + '»');
    }
  }

  const words = html.replace(/<!--[\s\S]*?-->/g, '').replace(/<[^>]+>/g, ' ')
    .trim().split(/\s+/).filter(Boolean).length;

  if (errs.length) {
    bad++;
    console.log('🔴 ' + f);
    errs.forEach((e) => console.log('     ' + e));
  } else {
    console.log('✅ ' + f.padEnd(38) + String(words).padStart(4) + ' كلمة  · نِسَب: ' + (used.join('/') || 'ولا وحدة'));
  }
}

console.log('');
if (bad) { console.error('🔴 ' + bad + ' من ' + files.length + ' فيهم مشاكل'); process.exit(1); }
console.log('✅ ' + files.length + ' مقالات · النِسَب والأزواج والأعداد من الكتالوج+ووكومرس · والروابط حيّة');
