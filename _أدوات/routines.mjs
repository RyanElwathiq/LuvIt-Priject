/** رقم عربي منطوق · للكوبي */
export function منطوق(n, مؤنث = false) {
  const م = { 2: 'روتينان', 3: 'تلات', 4: 'أربع', 5: 'خمس', 6: 'ست' };
  return م[n] || String(n);
}

/** العدد معرَّفاً · «المنتجات الأربعة».
 *  ⚠️ «منتجات» جمع تكسير، فالعدد ٣-١٠ بياخد **الصيغة المذكّرة**:
 *     المنتجات الأربعة · لا الأربع. و«الـ» + «أربع» بتطلع «الـأربع»
 *     وهاد اللي طلع فعلاً لما اشتققت العدد بلا صيغة معرَّفة. */
export function معرَّف(n) {
  const م = { 2: 'الاثنين', 3: 'الثلاثة', 4: 'الأربعة', 5: 'الخمسة', 6: 'الستة' };
  return م[n] || ('الـ' + n);
}
