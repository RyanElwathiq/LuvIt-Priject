#!/usr/bin/env node
/**
 * ============================================================================
 * عناوين وأوصاف البحث · build-seo-meta.mjs
 * ============================================================================
 *   node _أدوات/build-seo-meta.mjs          يبني ويفحص
 *   node _أدوات/build-seo-meta.mjs --json   يطبع JSON للدفع بالمتصفح
 *
 * ── 🔴 ليش انبنى ─────────────────────────────────────────────────────────
 * `library/seo-meta.json` كان **مكتوباً بالإيد**، وضلّ على نموذج نوع البشرة
 * بعد ما تحوّل الموقع للهدف · فطلعت على جوجل:
 *
 *     /routines/glow/       →  «روتين البشرة المختلطة»   🔴 صفحة تانية أصلاً
 *     /routines/hydration/  →  «روتين البشرة الجافة»
 *     /routines/clarify/    →  «روتين البشرة الدهنية»
 *
 * وأخطر من هيك: الملف فيه مدخلات لـ212 و213 و214 بالأسماء القديمة،
 * **وهالأرقام صارت لصفحات تانية** · فدفع الملف كما هو كان بيكتب وصف
 * «الدهنية» على «التنقية والتوازن» وهكذا. **بيانات بايتة بتضرّ أكثر من
 * غيابها لأنها بتنكتب بثقة.**
 *
 * ⤷ صفحات الروتينات صارت **مشتقّة من `routines.mjs`** · تنضاف روتين،
 *   بينضاف وصفه لحاله.
 *
 * ── 🔴 والموضعة ──────────────────────────────────────────────────────────
 * ريّان ٢ أيلول: «غلط ينذكروا [النِسَب] كأنها الميزة الأساسية عننا · هاي
 * مصيبة لأنها بديهيات». الأوصاف كانت بتبلّش فيها.
 * الميزة: **مبني على حاجة الزبونة · ومرافقة قبل الطلب وبعده.**
 * ============================================================================
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROUTINES, عدد, منطوق } from './routines.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..');
const OUT = path.join(REPO, 'library', 'seo-meta.json');

/* أرقام صفحات الروتينات · الجسر الوحيد بين المفتاح ورقم ووردبريس */
const PAGE = { hydration: 213, glow: 214, clarify: 212, eventone: 368 };

/* 🔴 اسم العلامة · لاتيني دايماً · ريّان ٢ أيلول: «كلمة ما بتتعرب أصلاً».
   وبلا علامة تعجّب: القياس أثبت إنّ «Luv it!» جوّا نص عربي بتنرسم
   «!Luv it» · وووردبريس بيشيل محرف الاتجاه اللي بيصلّحها من اسم الموقع.
   والشعار بيضل «Luv it!» لأنه صورة وما بيتأثر بالاتجاه. */
const العلامة = 'Luv it';

/* اللاحقة · نفس اللي بيركّبه Rank Math على الصفحات اللي بلا عنوان مخصّص
   (مقيس على صفحة منتج: «سيروم فيتامين سي - Luv it»).
   🔴 وهون لازم تنكتب صريحة: العنوان المخصّص بيدهس قالب Rank Math كاملاً،
      فبلاها الصفحة بتضل بلا اسم علامة بنتائج البحث. */
const لاحقة = ' - ' + العلامة;

const ثابتة = [
  { id: 40, slug: 'home',
    title: العلامة + ' · روتين عناية مبني على حاجة بشرتك',
    description: 'منسألك عن بشرتك ومنبنيلك روتين على قدّ حاجتك · ومنرافقك قبل الطلب وبعده. الدفع عند الاستلام وتوصيل لكل محافظات الأردن.' },
  { id: 206, slug: 'products',
    title: 'المنتجات · التشكيلة كاملة',
    description: 'التشكيلة كاملة · منتجات مفردة وروتينات جاهزة مرتّبة بترتيب استعمالها، ومنساعدك تختاري اللي بيناسب بشرتك فعلاً. الدفع عند الاستلام.' },
  { id: 228, slug: 'about',
    title: 'من نحن · منبنيلك روتين مش منبيعك منتجات',
    description: العلامة + ' عناية بشرة بالأردن · منسألك عن بشرتك أول ومنركّب الخطوات على قدّ حاجتك، ومنرافقك قبل الطلب وبعده. الدفع عند الاستلام.' },
  { id: 211, slug: 'routines',
    title: 'الروتينات · ' + منطوق(عدد) + 'ة حسب هدفك',
    description: منطوق(عدد) + ' روتينات كاملة حسب هدفك · كل خطوة بمنتجها وترتيبها، ومنساعدك تختاري اللي بيناسبك. وسعر الروتين مجموع قطعه بالضبط، والدفع عند الاستلام.' },
  { id: 216, slug: 'quiz',
    title: 'اختبار البشرة · خمس أسئلة',
    description: 'خمس أسئلة قصيرة عن بشرتك، ومنقترحلك روتين كامل بخطواته على أساس إجاباتك. اقتراح مبني على إجاباتك · مش تشخيص طبي، وبتقدري تسألينا قبل ما تطلبي.' },
  { id: 226, slug: 'journal',
    title: 'المقالات · شرح بلا مبالغة',
    description: 'شرح مبسّط لشو بتعمل المكوّنات لبشرتك، وترتيب الروتين وكل قدّيش بتتقشّري وشو بتتوقّعي فعلاً · مكتوب بلا وعود ولا مبالغة، ولا رقم بلا مصدر.' },
  { id: 219, slug: 'shipping',
    title: 'الشحن والتوصيل',
    description: 'توصيل لكل محافظات الأردن والدفع عند الاستلام · ما في دفع مسبق ولا بطاقة. وأجرة التوصيل بتبيّنلك بصفحة إتمام الطلب قبل ما تأكّدي.' },
  { id: 220, slug: 'faq',
    title: 'الأسئلة الشائعة',
    description: 'كل الأسئلة عن الطلب والدفع عند الاستلام والتوصيل والمنتجات والاستبدال وتتبّع الطلب · مجموعة بمكان واحد، وإذا سؤالك مش هون اسألينا.' },
  { id: 210, slug: 'track',
    title: 'تتبّع طلبي',
    description: 'اكتبي رقم الطلب والإيميل اللي طلبتِ فيه، وبتشوفي حالة طلبك على طول. ورقم الطلب بيطلعلك بصفحة تأكيد الطلب وبيوصلك بالإيميل.' },
];

/* 🔴 صفحات الروتينات مشتقّة · وأي روتين بلا رقم صفحة بيوقف البناء */
const روتينات = ROUTINES.map((r) => {
  const id = PAGE[r.key];
  if (!id) { console.error('🔴 روتين ' + r.key + ' بلا رقم صفحة بـPAGE'); process.exit(1); }
  const خطوات = منطوق(r.steps.length);
  return {
    id, slug: r.key,
    title: r.ar,
    description: r.sub.replace(/\s+/g, ' ').trim() +
      ' ' + خطوات + ' خطوات بترتيبها، وسعر الروتين مجموع قطعه بالضبط.',
  };
});

const pages = [...ثابتة, ...روتينات]
  .map((p) => (p.title.includes(العلامة) ? p : { ...p, title: p.title + لاحقة }))
  .sort((a, b) => a.id - b.id);

/* ── بوابات ─────────────────────────────────────────────────────────── */
const errs = [];
const seen = new Set();
for (const p of pages) {
  if (seen.has(p.id)) errs.push('رقم مكرّر: ' + p.id);
  seen.add(p.id);
  if (p.title.length > 60) errs.push(p.slug + ' · العنوان ' + p.title.length + ' حرف (السقف ٦٠)');
  const d = p.description.length;
  if (d < 110 || d > 165) errs.push(p.slug + ' · الوصف ' + d + ' حرف (المدى ١١٠-١٦٥)');
  if (/—/.test(p.title + p.description)) errs.push(p.slug + ' · شرطة طويلة');
  /* 🔴 الاسم المعرَّب ممنوع نهائياً · ريّان ٢ أيلول */
  if (/(?<![؀-ۿ])لَ?ف\s*[إا]ت(?![؀-ۿ])/.test(p.title + p.description)) {
    errs.push(p.slug + ' · اسم العلامة معرَّباً · لازم يكون «' + العلامة + '»');
  }
  /* واللاحقة لازم تكون بكل عنوان · وإلا الصفحة بتضل بلا علامة بجوجل */
  if (!p.title.includes(العلامة)) {
    errs.push(p.slug + ' · العنوان بلا اسم العلامة');
  }
  /* 🔴 الموضعة · النِسَب بديهية مش ميزة */
  if (/نِسَب مكتوب|مكتوبة على العبوة|مطبوعة على العبوة|قابل للفحص على العبوة|الرقم هو اللي بيحاسبنا|مكوّنات واضحة/.test(p.title + p.description)) {
    errs.push(p.slug + ' · الوصف بيبيع كتابة النِسَب · وهي بديهية');
  }
  /* والنموذج القديم */
  if (/حسب نوع البشرة|نوع بشرتك|دهنية وجافة/.test(p.description + p.title)) {
    errs.push(p.slug + ' · نموذج نوع البشرة انتهى');
  }
}
if (errs.length) {
  console.error('🔴 أوصاف مرفوضة:');
  errs.forEach((e) => console.error('     ' + e));
  process.exit(1);
}

const j = {
  _ملاحظة: 'مولَّد بـ_أدوات/build-seo-meta.mjs · لا تعدّله بالإيد · صفحات الروتينات مشتقّة من routines.mjs',
  _قواعد: [
    'كل وصف بيوصف اللي موجود بالصفحة فعلاً · ولا وعد ولا رقم ولا مدة',
    'الزبونة تُخاطَب بالمؤنث',
    'ولا شرطة طويلة · النقطة الوسطى (·) بدلها',
    'العنوان تحت ٦٠ حرف والوصف بين ١١٠ و١٦٥',
    '🔴 الميزة: مبني على حاجة الزبونة ومرافقة قبل الطلب وبعده · **مش** كتابة النِسَب',
    '🔴 السلة والشيك أوت وحسابي noindex فما بدهم أوصافاً',
  ],
  pages,
};

if (process.argv.includes('--json')) { console.log(JSON.stringify(pages)); process.exit(0); }
fs.writeFileSync(OUT, JSON.stringify(j, null, 1) + '\n', 'utf8');
console.log('✅ ' + pages.length + ' صفحة · ' + روتينات.length + ' منها مشتقّة من routines.mjs');
for (const p of pages) {
  console.log('  ' + String(p.id).padStart(4) + '  ' + p.slug.padEnd(11) +
    String(p.title.length).padStart(3) + '/' + String(p.description.length).padStart(3) + '  ' + p.title);
}
